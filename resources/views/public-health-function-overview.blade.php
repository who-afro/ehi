        <h2>Disease prevention</h2>
        <p>Prevention, as it relates to health, is about avoiding disease before it starts. It is defined as the
            plans for, and the measures taken, to prevent the onset of a disease or other health problem before
            the occurrence of the undesirable health event. There are three distinct levels of prevention.
            The primordial level of prevention is a population health approach which includes actions that are
            taken to prevent future hazards to health and to decrease those factors which are known to increase
            the risks of disease. In this case the broad determinants of health are addressed rather than
            individual exposure to risk factors. Examples of primordial prevention initiatives include improving
            sanitation, promoting healthy lifestyles in childhood,</p>
        <ol>
            <li>Primary prevention—those preventive measures that prevent the onset of illness or injury before
                the disease process begins.e.g. immunization and regular exercise.
            </li>
            <li>Secondary prevention—those preventive measures that lead to early diagnosis and prompt treatment
                of a disease, illness, or injury to prevent more severe problems developing. e.g., screening for
                high blood pressure and breast self-examination.
            </li>
            <li>Tertiary prevention—those preventive measures aimed at reversing, arresting or delaying disease.
                It helps to lessen the impact of disease on the patient’s overall life. The patient has more
                contact with the healthcare system, and care providers in many roles and settings.
            </li>
        </ol>
        <h2>Curative services</h2>
        Curative care refers to treatment and therapies provided to a patient with the main intent of fully resolving an
        illness and the goal of bringing the patient—ideally—to their status of health before the illness presented
        itself. The care is therefore focused on intent of curing and not just reducing pain or stress. For instance,
        when a patient receives curative care for Breast Cancer, the goal is for any anatomical evidence of the cancer
        to disappear and for that patient's overall health to return to its status from before the cancer was diagnosed.
        <h2>Rehabilitation care</h2>
        Rehabilitative/Rehabilitation Services Health care services are aimed at helping one to get back or improve
        skills and functioning for daily living that have been lost or impaired because sickness, injury or disability.
        The services are meant to restore abilities that were lost and minimise physical or mental limitations. The
        rehabilitation measures therefore promote optimum attainable levels of physical, cognitive, emotional,
        psychological, social, and economic usefulness, and also to maintain the individual at the maximal functional
        level. Rehabilitation services help people return to daily life and live in a normal or near-normal way. The
        examples of types of rehabilitation services include, occupational, physical and speech. Each form of
        rehabilitation serves a unique purpose in helping a person reach full recovery, but all share the ultimate goal
        of helping the patient return to a healthy and active lifestyle.
        <h2>Palliative care</h2>
        Palliative care is an interdisciplinary medical caregiving approach aimed at optimizing quality of life and
        mitigating suffering among people with serious, complex illness. The World Health Organization describes
        palliative care as "an approach that improves the quality of life of patients and their families facing the
        problems associated with life-threatening illness, through the prevention and relief of suffering by means of
        early identification and impeccable assessment and treatment of pain and other problems, physical, psychosocial,
        and spiritual". Palliative care is therefore aimed at providing relief from the symptoms and stress of the
        illness. The goal is to improve quality of life for both the patient and the family.
